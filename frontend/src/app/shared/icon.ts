export type IconName = keyof typeof PATHS;

/** Habit ids map to icons here; habits a learner adds themselves get a plain dot. */
const HABIT_ICONS: Record<string, string> = {
  plan: 'calendar', dsa: 'code', learn: 'book', recall: 'message', trap: 'alert', focus: 'timer', apply: 'send',
  journal: 'pen',
};
export const habitIcon = (id: string) => HABIT_ICONS[id] ?? 'dot';
const HABIT_TONES: Record<string, string> = {
  plan: 'plan', dsa: 'dsa', learn: 'core', recall: 'core', trap: 'traps', focus: 'plan', apply: 'final', journal: 'neutral',
};
/** The site area a habit belongs to, which picks its colour. */
export const habitTone = (id: string) => HABIT_TONES[id] ?? 'neutral';

